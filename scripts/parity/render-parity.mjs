#!/usr/bin/env node
// Renders docs/polymer-parity.md from contracts/polymer-slots.json, the curated
// contracts/polymer-contribution-map.json and contracts/polymer-slot-hosts.json, and
// contracts/contribution-identities.json.
// `--check` fails when the committed document differs from the rendering.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const DOCUMENT = 'docs/polymer-parity.md';
const json = (file) => JSON.parse(readFileSync(path.join(root, file), 'utf8'));
const code = (value) => `\`${value}\``;
const cell = (value) => String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
const runtimeSources = (directory) =>
	readdirSync(path.join(root, directory), { withFileTypes: true }).flatMap((entry) => {
		const name = `${directory}/${entry.name}`;
		if (entry.isDirectory()) return name === 'app/testing' ? [] : runtimeSources(name);
		return /\.(ts|html)$/.test(name) && !/\.(spec|generated)\.ts$/.test(name) ? [name] : [];
	});
// A provider name as its own token; dotted message keys such as pageProviders.<name>.* do not count.
export const providerReferences = (name, files) =>
	files.filter((file) =>
		new RegExp(`(?<![\\w.])${name}(?![\\w.])`).test(readFileSync(path.join(root, file), 'utf8')),
	);

export async function render() {
	const slots = json('contracts/polymer-slots.json');
	const map = json('contracts/polymer-contribution-map.json').contributions;
	const identities = json('contracts/contribution-identities.json').slots;
	const hostMap = json('contracts/polymer-slot-hosts.json').slots;
	const lines = [
		'# Polymer slot parity',
		'',
		'<!-- Generated by scripts/parity/render-parity.mjs; edit the contracts, then run npm run render:polymer-parity. -->',
		'',
		`Compares the slot hosts and default contributions of Polymer Nuxeo Web UI ${code(slots.revision.slice(0, 9))} (${slots.source}, Apache-2.0) with this repository's defaults. A migrated Polymer override that names a Polymer default targets the Angular IDs listed here.`,
		'',
		'Status: **mapped** has Angular equivalents, **gap** has none in core, **addon** comes from a Polymer add-on this repository does not ship. Host placement and slot-model fields are compared under Hosts and Slot models.',
		'',
		'## Slots',
		'',
		'| Slot | Polymer hosts | Polymer defaults | Mapped | Gaps | Add-on | Angular defaults |',
		'| --- | --- | --- | --- | --- | --- | --- |',
	];
	for (const slot of identities) {
		const hosts = slots.hosts.filter((host) => host.slot === slot.name).length;
		const entries = map.filter((entry) => entry.slot === slot.name);
		const count = (status) => entries.filter((entry) => entry.status === status).length;
		lines.push(
			`| ${code(slot.name)} | ${hosts || 'none (Angular only)'} | ${entries.length} | ${count('mapped')} | ${count('gap')} | ${count('addon')} | ${slot.contributions.length} |`,
		);
	}
	lines.push(
		'',
		'## Hosts',
		'',
		'Where each slot renders. Placement: **same** matches the Polymer location, **moved** renders elsewhere, **partial** lacks some Polymer locations, **angular-only** has no Polymer host. `verify:polymer-parity` checks the host components against the source.',
		'',
		'| Slot | Placement | Polymer | Angular | Host components | Note |',
		'| --- | --- | --- | --- | --- | --- |',
		...hostMap.map(
			(entry) =>
				`| ${code(entry.slot)} | ${entry.placement} | ${cell(entry.polymer ?? '–')} | ${cell(entry.angular)} | ${entry.hosts.map((file) => code(path.basename(file, '.ts'))).join(', ')} | ${cell(entry.note ?? '')} |`,
		),
		'',
		'## Slot models',
		'',
		`Polymer merges a shared model (${slots.sharedModel.fields.map(code).join(', ')}, set in ${code(slots.sharedModel.file)}) into every slot's model, and each host adds its own fields. Angular's slot hosts (\`nx-webui-slot\`, \`nx-document-views\`) add the signed-in user from \`WebUiAppState\` the same way; a host's own \`user\` wins. The rest of nuxeo-app's model (clipboard, tasks, personal workspace, route, Nuxeo URL) is read from \`WebUiAppState\`. Status: **mapped** has Angular context properties, **replaced** has an SDK API outside the context, **gap** has none, **dropped** has no use to carry over. \`verify:polymer-parity\` checks the Angular properties against each slot's context type.`,
		'',
		'| Slot | Polymer field | Status | Angular | Note |',
		'| --- | --- | --- | --- | --- |',
		...hostMap.flatMap((entry) =>
			entry.fields.map(
				(field) =>
					`| ${code(entry.slot)} | ${code(field.polymer)} | ${field.status} | ${(field.angular ?? []).map(code).join(', ') || '–'} | ${cell(field.note ?? '')} |`,
			),
		),
	);
	const modes = ['create', 'edit', 'import', 'metadata', 'view'];
	lines.push(
		'',
		'## Document layouts',
		'',
		"Polymer's `nuxeo-document-layout` loads `<type>/nuxeo-<type>-<mode>-layout.html`, both lowercased, and shows a not-found error when the file is missing. Every Polymer per-type layout resource at this revision is registered in `default-document-layouts.ts`; `verify:polymer-parity` checks the list.",
		'',
		'| Mode | Polymer resources |',
		'| --- | --- |',
		...modes.map(
			(mode) =>
				`| ${code(mode)} | ${slots.layouts.filter((layout) => layout.mode === mode).length} |`,
		),
		'',
		'`DocumentLayoutRegistry` matches the lowercased type and the mode, then applies priority and `when`. Where Polymer shows a not-found error, the view, create/edit and import hosts fall back to a generic component. Polymer has no list or grid card layouts; `provideResultsProjections()` replaces cards per type.',
		'',
		// Hand-written guidance kept beside the renderer so regeneration preserves it.
		readFileSync(path.join(root, 'scripts/parity/custom-type-layouts.md'), 'utf8').trimEnd(),
	);
	const parity = json('contracts/polymer-contribution-map.json');
	const themeIds = new Set(
		identities.find((slot) => slot.name === 'THEMES')?.contributions.map((entry) => entry.id),
	);
	const workflowKeys = new Set(
		[
			...readFileSync(
				path.join(root, 'app/modules/explorer/components/workflows/default-workflow-layouts.ts'),
				'utf8',
			).matchAll(/'(task[0-9a-f]+)'/g),
		].map((match) => match[1]),
	);
	const sources = runtimeSources('app');
	lines.push(
		'',
		'## Non-slot customizations',
		'',
		'Polymer customization resources outside slots and document layouts. Status: **supported** has an SDK registration API, **server** needs no UI migration, **waived** has no SDK equivalent and follows the guidance.',
		'',
		'| Surface | Polymer resources | Status | Angular |',
		'| --- | --- | --- | --- |',
		...parity.surfaces.map(
			(surface) =>
				`| ${surface.surface} | ${surface.inventory ? slots[surface.inventory].length : '–'} | ${surface.status} | ${cell(surface.angular)} |`,
		),
		'',
		'### Guidance',
		'',
		...parity.surfaces.map((surface) => `- **${surface.surface}**: ${surface.guidance}`),
		'',
		'### Searches',
		'',
		'`nuxeo-search-form` loads `search/<name>/nuxeo-<name>-search-form.html` and its `-search-results.html`.',
		'',
		'| Polymer search | Status | Angular | Note |',
		'| --- | --- | --- | --- |',
		...parity.searches.map(
			(entry) =>
				`| ${code(entry.polymer)} | ${entry.status} | ${entry.angular.map((target) => `${code(target.id)} (${target.slot})`).join(', ') || '–'} | ${cell(entry.note ?? '')} |`,
		),
		'',
		'### Workflow task layouts',
		'',
		'`nuxeo-document-task` loads `<workflow model>/nuxeo-<task node>-layout.html`.',
		'',
		'| Workflow | Task | Angular default |',
		'| --- | --- | --- |',
		...slots.workflowLayouts.map(
			(layout) =>
				`| ${code(layout.model)} | ${code(layout.task)} | ${workflowKeys.has(layout.task) ? code(`nuxeo.${layout.task}`) : 'missing'} |`,
		),
		'',
		'### Themes',
		'',
		'| Polymer theme | Angular default |',
		'| --- | --- |',
		...slots.themes.map((theme) => {
			const id = `maretha.theme.${theme.name}`;
			return `| ${code(theme.name)} | ${themeIds.has(id) ? code(id) : 'missing'} |`;
		}),
		'',
		'### Page providers',
		'',
		'Server page provider names that Polymer elements reference literally, and the Angular runtime files that reference the same name.',
		'',
		'| Page provider | Polymer origin | Angular runtime files |',
		'| --- | --- | --- |',
		...slots.pageProviders.map(
			(provider) =>
				`| ${code(provider.name)} | ${provider.origins.join(', ')} | ${providerReferences(provider.name, sources).length || 'none'} |`,
		),
	);
	const gaps = map.filter((entry) => entry.status === 'gap');
	lines.push('', '## Gaps', '', '### Contributions', '');
	for (const entry of gaps)
		lines.push(`- ${code(entry.slot)} ${code(entry.polymer)}: ${entry.note}`);
	lines.push('', '### Placement', '');
	for (const entry of hostMap.filter((entry) => ['moved', 'partial'].includes(entry.placement)))
		lines.push(`- ${code(entry.slot)} (${entry.placement}): ${entry.note}`);
	// One line per missing field and reason, naming every slot it affects.
	const fieldGaps = new Map();
	for (const entry of hostMap)
		for (const field of entry.fields.filter((field) => field.status === 'gap')) {
			const key = `${code(field.polymer)}: ${field.note}`;
			fieldGaps.set(key, [...(fieldGaps.get(key) ?? []), entry.slot]);
		}
	lines.push('', '### Model fields', '');
	for (const [key, affected] of fieldGaps) {
		const [field, note] = key.split(/: (.*)/s);
		lines.push(`- ${field} in ${affected.map(code).join(', ')}: ${note}`);
	}
	lines.push('', '## Contributions', '');
	for (const slot of identities) {
		const entries = map.filter((entry) => entry.slot === slot.name);
		if (!entries.length) continue;
		lines.push(
			`### ${slot.name}`,
			'',
			'| Polymer | Origin | Status | Angular | Note |',
			'| --- | --- | --- | --- | --- |',
		);
		for (const entry of entries)
			lines.push(
				`| ${code(entry.polymer)} | ${entry.origin} | ${entry.status} | ${entry.angular.map(code).join(', ') || '–'} | ${cell(entry.note ?? '')} |`,
			);
		lines.push('');
	}
	const options = await prettier.resolveConfig(path.join(root, DOCUMENT));
	return prettier.format(lines.join('\n'), { ...options, parser: 'markdown' });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const target = path.join(root, DOCUMENT);
	const text = await render();
	if (!process.argv.includes('--check')) writeFileSync(target, text);
	else if (readFileSync(target, 'utf8') !== text) {
		console.error(`${DOCUMENT} is stale; run npm run render:polymer-parity.`);
		process.exitCode = 1;
	}
}
