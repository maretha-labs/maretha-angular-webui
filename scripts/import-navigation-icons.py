"""Import sidebar SVGs from the bundle served by the reference Nuxeo Web UI."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--bundle', type=Path, required=True)
parser.add_argument('--version', required=True, help='Reference Web UI bundle version')
args = parser.parse_args()
root = Path(__file__).resolve().parent.parent
source = args.bundle.read_text()


def iconset(name):
    matches = re.findall(
        rf'<iron-iconset-svg\b(?=[^>]*\bname="{name}")(?=[^>]*\bsize="24")[^>]*>(.*?)</iron-iconset-svg>',
        source, re.S,
    )
    if len(matches) != 1:
        raise SystemExit(f'Expected exactly one {name} iconset, found {len(matches)}')
    # Webpack keeps these template literals as strings with escaped newlines.
    markup = matches[0].replace('\\n', '\n')
    return markup


def node(element):
    result = {
        'tag': element.tag,
        'attributes': {key: value for key, value in element.attrib.items() if key != 'id'},
    }
    if len(element):
        result['children'] = [node(child) for child in element]
    return result


sources = {'nuxeo': iconset('nuxeo'), 'icons': iconset('icons')}
names = ['create', 'browse', 'recent', 'search', 'expired', 'tasks', 'favorites',
         'collections', 'user-space', 'clipboard', 'delete', 'admin', 'user-settings']
icons = {}
for name in names + ['assets']:
    family, source_name = ('icons', 'perm-media') if name == 'assets' else ('nuxeo', name)
    match = re.search(rf'<g\s+id="{source_name}"(?:\s[^>]*)?>', sources[family])
    if not match:
        raise SystemExit(f'Missing reference icon: {family}:{source_name}')
    # Parse just the selected group so unrelated upstream markup cannot affect this import.
    remaining = sources[family][match.start():]
    depth = 0
    for tag in re.finditer(r'</?g\b[^>]*>', remaining):
        depth += -1 if tag.group().startswith('</') else 1
        if depth == 0:
            element = ET.fromstring(remaining[:tag.end()])
            break
    else:
        raise SystemExit(f'Unclosed reference icon: {family}:{source_name}')
    icons[f'nuxeo-navigation:{name}'] = {'viewBox': '0 0 24 24', 'nodes': [node(element)]}

license_file = root / 'app/extensions/nuxeo-icons.generated.ts'
license_notice = license_file.read_text().split('*/', 1)[0] + '*/'
provenance = '\n'.join([
    '// Generated by scripts/import-navigation-icons.py; do not edit SVG geometry.',
    f'// Reference: Nuxeo Web UI served ui/main.bundle.js ({args.version}).',
    f'// Source SHA-256: {hashlib.sha256(args.bundle.read_bytes()).hexdigest()}',
    '// Scoped names preserve the existing icons used by document views.',
])
target = root / 'app/modules/shared/components/sidebar/navigation-icons.generated.ts'
target.write_text(
    license_notice + '\n' + provenance
    + '\nimport { WebUiIcon } from "@maretha/webui-sdk";\n\n'
    + 'export const NAVIGATION_ICONS: Readonly<Record<string, WebUiIcon>> = '
    + json.dumps(icons, ensure_ascii=False, indent=2) + ';\n'
)
print(f'Imported {len(icons)} navigation icons from {args.bundle.name}')
